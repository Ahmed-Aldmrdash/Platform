function answerPlatform(question, ctx) {
  const nq = normalizeArabic(question);
  const admin = isAdmin(ctx && ctx.user && ctx.user.role);
  for (const entry of ENTRIES) {
    if (entry.re.test(nq)) {
      return { reply: entry.reply(admin), source: entry.source || SOURCE };
    }
  }
  return null;
}

